static void test_the_angles_and_speeds_stay_in_range(void) {
    static const uint32_t seeds[] = {1984u, 1u, 42u, 7u};
    for (size_t k = 0; k < sizeof seeds / sizeof seeds[0]; k++) {
        swc_city_build(&city, seeds[k]);
        swc_tour_init(&tour, &city, seeds[k]);
        double max_roll = 0.0;
        for (int i = 0; i <= 2400; i++) {
            SwcTourSample s;
            swc_tour_sample(&tour, 0.5 * (double)i, &s);
            CHECK(s.x >= 0.0 && s.x < SWC_TILE && s.z >= 0.0 && s.z < SWC_TILE);
            CHECK(s.yaw >= -SWC_PI - 1e-9 && s.yaw < SWC_PI + 1e-9);
            CHECK(fabs(s.pitch) <= 1.2 + 1e-9);
            CHECK(s.speed > 5.0 && s.speed < 80.0);
            CHECK(s.y > 3.0 && s.y < 1000.0);
            if (fabs(s.roll) > max_roll)
                max_roll = fabs(s.roll);
        }
        CHECK(max_roll <= SWC_TOUR_MAX_ROLL + 1e-9);
        CHECK(max_roll > 0.05); /* the tour does bank into turns */
    }
    swc_city_build(&city, 1984u);
}

static void test_the_tour_never_touches_a_building(void) {
    static const uint32_t seeds[] = {1984u, 3u, 99u};
    for (size_t k = 0; k < sizeof seeds / sizeof seeds[0]; k++) {
        swc_city_build(&city, seeds[k]);
        swc_tour_init(&tour, &city, seeds[k]);
        int touched = 0;
        for (int i = 0; i <= 6000; i++) {
            SwcTourSample s;
            swc_tour_sample(&tour, 0.4 * (double)i, &s);
            SwcVec3 p = {s.x, s.y, s.z};
            if (swc_city_collide(&city, &p, 1.8))
                touched++;
        }
        CHECK_EQ_INT(touched, 0);
    }
    swc_city_build(&city, 1984u);
}

static void test_the_motion_is_smooth(void) {
    swc_tour_init(&tour, &city, 1984u);
    SwcTourSample prev, s;
    swc_tour_sample(&tour, 0.0, &prev);
    double worst_turn = 0.0;
    for (int i = 1; i <= 3000; i++) {
        double t = 0.1 * (double)i;
        swc_tour_sample(&tour, t, &s);
        double dx = swc_wrap_delta(s.x, prev.x, SWC_TILE), dz = swc_wrap_delta(s.z, prev.z, SWC_TILE);
        double dy = s.y - prev.y;
        double step = sqrt(dx * dx + dy * dy + dz * dz);
        /* The path is the integral of the velocity. */
        CHECK(fabs(step - 0.1 * s.speed) < 0.1 * 6.0);
        double turn = fabs(swc_wrap_delta(s.yaw, prev.yaw, SWC_TAU));
        if (turn > worst_turn)
            worst_turn = turn;
        prev = s;
    }
    /* No snap: the view never turns more than ~0.6 rad in a tenth of a second. */
    CHECK(worst_turn < 0.6);
}

