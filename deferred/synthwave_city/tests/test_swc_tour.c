static void test_a_restart_begins_at_the_given_point_and_heading(void) {
    SwcTourStart st = {1600.0, 200.0, 3200.0, 3};
    swc_tour_init(&tour, &city, 1984u);
    swc_tour_restart(&tour, &st, 77u);
    SwcTourSample s;
    swc_tour_sample(&tour, 0.0, &s);
    CHECK_NEAR(s.x, 1600.0, 1e-6);
    CHECK_NEAR(s.y, 200.0, 1e-6);
    CHECK_NEAR(s.z, 3200.0, 1e-6);
    CHECK(s.vx > 0.0); /* heading 3: +x */
    CHECK_NEAR(s.vz, 0.0, 1e-9);
    /* A point off the road line is snapped onto it: 3123 is nearest the line at 3200. */
    SwcTourStart off = {1700.0, 60.0, 3123.0, 3};
    swc_tour_restart(&tour, &off, 77u);
    swc_tour_sample(&tour, 0.0, &s);
    CHECK_NEAR(s.x, 1700.0, 1e-6);
    CHECK_NEAR(s.z, 3200.0, 1e-6);
}

