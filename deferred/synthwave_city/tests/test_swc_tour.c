static void test_the_pose_matches_the_web_version(void) {
    for (size_t c = 0; c < sizeof GOLDEN / sizeof GOLDEN[0]; c++) {
        const GoldenCase *g = &GOLDEN[c];
        swc_city_build(&city, g->seed);
        swc_tour_init(&tour, &city, g->seed);
        if (g->start.heading >= 0 || g->restart_seed != g->seed)
            swc_tour_restart(&tour, g->start.heading >= 0 ? &g->start : NULL, g->restart_seed);
        for (int r = 0; r < GOLDEN_TIMES; r++) {
            const double *row = g->rows[r];
            SwcTourSample s;
            swc_tour_sample(&tour, row[0], &s);
            /* Positions are tile metres up to 6400: a part in 10^9 of that is far below a pixel. */
            CHECK_NEAR(s.x, row[1], 2e-6);
            CHECK_NEAR(s.y, row[2], 2e-6);
            CHECK_NEAR(s.z, row[3], 2e-6);
            CHECK_NEAR(s.yaw, row[4], 1e-9);
            CHECK_NEAR(s.pitch, row[5], 1e-9);
            CHECK_NEAR(s.roll, row[6], 1e-9);
            CHECK_NEAR(s.vx, row[7], 1e-9);
            CHECK_NEAR(s.vy, row[8], 1e-9);
            CHECK_NEAR(s.vz, row[9], 1e-9);
            CHECK_NEAR(s.speed, row[10], 1e-9);
        }
    }
    swc_city_build(&city, 1984u);
}

static void test_the_pose_is_a_pure_function_of_time(void) {
    swc_tour_init(&tour, &city, 1984u);
    swc_tour_init(&other, &city, 1984u);
    SwcTourSample a, b;
    /* One tour is walked forward in small steps, the other jumps straight to each time. */
    for (int i = 0; i <= 800; i++) {
        double t = 0.5 * (double)i;
        swc_tour_sample(&tour, t, &a);
        if (i % 97 == 0) {
            swc_tour_sample(&other, t, &b);
            CHECK_NEAR(a.x, b.x, 1e-6);
            CHECK_NEAR(a.y, b.y, 1e-6);
            CHECK_NEAR(a.z, b.z, 1e-6);
            CHECK_NEAR(a.yaw, b.yaw, 1e-9);
            CHECK_NEAR(a.pitch, b.pitch, 1e-9);
            CHECK_NEAR(a.roll, b.roll, 1e-9);
        }
    }
    /* Going back in time regenerates from the start and gets the same answer. */
    SwcTourSample first, again;
    swc_tour_sample(&tour, 40.0, &first);
    swc_tour_sample(&tour, 900.0, &a);
    swc_tour_sample(&tour, 40.0, &again);
    CHECK_NEAR(first.x, again.x, 1e-6);
    CHECK_NEAR(first.y, again.y, 1e-6);
    CHECK_NEAR(first.z, again.z, 1e-6);
    CHECK_NEAR(first.yaw, again.yaw, 1e-12);
}

