static void test_the_atlas_layout_matches_the_web_version(void) {
    CHECK_EQ_INT(swc_atlas_layout(cells), SWC_ATLAS_CELL_COUNT);
    CHECK_EQ_INT(GOLDEN_CELL_COUNT, SWC_ATLAS_CELL_COUNT);
    for (int i = 0; i < GOLDEN_CELL_COUNT; i++) {
        CHECK_EQ_INT(cells[i].kind, GOLDEN_CELLS[i].kind);
        CHECK_EQ_INT(cells[i].index, GOLDEN_CELLS[i].index);
        CHECK_EQ_INT(cells[i].x, GOLDEN_CELLS[i].x);
        CHECK_EQ_INT(cells[i].y, GOLDEN_CELLS[i].y);
        CHECK_EQ_INT(cells[i].w, GOLDEN_CELLS[i].w);
        CHECK_EQ_INT(cells[i].h, GOLDEN_CELLS[i].h);
    }
    for (int i = 0; i < GOLDEN_RECT_COUNT; i++) {
        float r[4];
        for (int inset = 1; inset <= 2; inset++) {
            swc_atlas_cell_rect(&cells[GOLDEN_RECT_CELLS[i]], inset, r);
            for (int k = 0; k < 4; k++)
                CHECK_NEAR(r[k], GOLDEN_RECTS[i][inset - 1][k], 1e-9);
        }
    }
}

static void test_every_cell_lies_in_the_canvas_and_none_overlap(void) {
    swc_atlas_layout(cells);
    for (int i = 0; i < SWC_ATLAS_CELL_COUNT; i++) {
        CHECK(cells[i].x >= 0 && cells[i].y >= 0);
        CHECK(cells[i].x + cells[i].w <= SWC_ATLAS_SIZE && cells[i].y + cells[i].h <= SWC_ATLAS_SIZE);
        for (int j = i + 1; j < SWC_ATLAS_CELL_COUNT; j++) {
            bool apart = cells[i].x + cells[i].w <= cells[j].x || cells[j].x + cells[j].w <= cells[i].x ||
                         cells[i].y + cells[i].h <= cells[j].y || cells[j].y + cells[j].h <= cells[i].y;
            CHECK(apart);
        }
    }
    const SwcAtlasCell *list[SWC_ATLAS_CELL_COUNT];
    CHECK_EQ_INT(swc_atlas_cells_of_kind(cells, SWC_CELL_WIDE, list, SWC_ATLAS_CELL_COUNT),
                 SWC_ATLAS_WIDE_COUNT);
    CHECK_EQ_INT(swc_atlas_cells_of_kind(cells, SWC_CELL_TALL, list, SWC_ATLAS_CELL_COUNT),
                 SWC_ATLAS_TALL_COUNT);
    CHECK_EQ_INT(swc_atlas_cells_of_kind(cells, SWC_CELL_STRIP, list, SWC_ATLAS_CELL_COUNT),
                 SWC_ATLAS_STRIP_COUNT);
    CHECK_EQ_INT(swc_atlas_cells_of_kind(cells, SWC_CELL_STRIP, list, 2), 2);
}

