static void test_the_wire_solids_match_the_web_version(void) {
    for (int i = 0; i < N_GOLDEN; i++) {
        const GoldenCase *g = &GOLDEN[i];
        build_case(g);
        int n = swc_holo_pick_objects(&city, g->density, picked, 256);
        CHECK_EQ_INT(n, g->objects);
        if (n > 0) {
            CHECK_NEAR(picked[0]->x, g->obj_first[0], 1e-9);
            CHECK_NEAR(picked[0]->y, g->obj_first[1], 1e-9);
            CHECK_NEAR(picked[0]->z, g->obj_first[2], 1e-9);
            CHECK_NEAR(picked[0]->w, g->obj_first[3], 1e-9);
            CHECK_EQ_INT(picked[0]->color, (int)g->obj_first[4]);
            CHECK_NEAR(picked[0]->seed, g->obj_first[5], 1e-12);
        }
        SwcWireMesh m;
        CHECK(swc_holo_build_wire(picked, n, &m));
        CHECK_EQ_INT(m.vertex_count, g->wire_vertices);
        CHECK_EQ_INT(m.object_count, g->shape_count);
        for (int k = 0; k < g->shape_count; k++)
            CHECK_EQ_INT(m.shapes[k], g->shapes[k]);
        double pos[3] = {0, 0, 0}, bary[3] = {0, 0, 0}, anchor[3] = {0, 0, 0}, spin[4] = {0, 0, 0, 0};
        double look[4] = {0, 0, 0, 0}, style[4] = {0, 0, 0, 0}, abs_pos = 0;
        for (int v = 0; v < m.vertex_count; v++) {
            const float *f = &m.data[(size_t)v * SWC_WIRE_STRIDE];
            for (int k = 0; k < 3; k++) {
                pos[k] += (double)f[SWC_WIRE_POSITION + k];
                bary[k] += (double)f[SWC_WIRE_BARY + k];
                anchor[k] += (double)f[SWC_WIRE_ANCHOR + k];
                abs_pos += fabs((double)f[SWC_WIRE_POSITION + k]);
            }
            for (int k = 0; k < 4; k++) {
                spin[k] += (double)f[SWC_WIRE_SPIN + k];
                look[k] += (double)f[SWC_WIRE_LOOK + k];
                style[k] += (double)f[SWC_WIRE_STYLE + k];
            }
        }
        for (int k = 0; k < 3; k++) {
            check_sum(pos[k], g->w_pos[k]);
            check_sum(bary[k], g->w_bary[k]);
            check_sum(anchor[k], g->w_anchor[k]);
        }
        for (int k = 0; k < 4; k++) {
            check_sum(spin[k], g->w_spin[k]);
            check_sum(look[k], g->w_look[k]);
            check_sum(style[k], g->w_style[k]);
        }
        check_sum(abs_pos, g->abs_pos);
        for (int k = 0; k < 9; k++) {
            CHECK_NEAR(m.data[SWC_WIRE_POSITION + (k / 3) * SWC_WIRE_STRIDE + k % 3], g->first_verts[k],
                       1e-5);
            int last = m.vertex_count - 3 + k / 3;
            CHECK_NEAR(m.data[(size_t)last * SWC_WIRE_STRIDE + SWC_WIRE_POSITION + k % 3], g->last_verts[k],
                       1e-5);
        }
        for (int k = 0; k < 8; k++) {
            CHECK_NEAR(m.data[(k / 4) * SWC_WIRE_STRIDE + SWC_WIRE_LOOK + k % 4], g->first_look[k], 0.0);
            int last = m.vertex_count - 2 + k / 4;
            CHECK_NEAR(m.data[(size_t)last * SWC_WIRE_STRIDE + SWC_WIRE_STYLE + k % 4], g->last_style[k],
                       0.0);
        }
        swc_holo_free_wire(&m);
    }
}

static void test_a_lower_density_keeps_a_subset_and_every_landmark_panel(void) {
    build_case(&GOLDEN[0]);
    SwcPanelPack full, thin;
    CHECK(swc_holo_pack_panels(&city, cells, 1.0, &full));
    CHECK(swc_holo_pack_panels(&city, cells, 0.1, &thin));
    CHECK(thin.count < full.count);
    int landmarks = 0;
    for (int s = 0; s < city.site_count; s++)
        landmarks +=
            city.sites[s].kind == SWC_SITE_HOLO_PANEL && city.sites[s].w >= SWC_HOLO_ALWAYS_KEEP_WIDTH;
    CHECK(thin.count >= landmarks);
    swc_holo_free_panels(&full);
    swc_holo_free_panels(&thin);
    SwcTickerPack tf, tt;
    CHECK(swc_holo_pack_tickers(&city, cells, 1.0, &tf));
    CHECK(swc_holo_pack_tickers(&city, cells, 0.0, &tt));
    CHECK(tt.count <= tf.count);
    CHECK(tt.count > 0); /* the lowest tier still keeps 60% of them */
    swc_holo_free_tickers(&tf);
    swc_holo_free_tickers(&tt);
}

static void test_a_panel_shows_two_different_ads_of_its_own_shape(void) {
    build_case(&GOLDEN[0]);
    SwcPanelPack p;
    CHECK(swc_holo_pack_panels(&city, cells, 1.0, &p));
    int seen_wide[SWC_ATLAS_WIDE_COUNT] = {0}, seen_tall[SWC_ATLAS_TALL_COUNT] = {0};
    for (int n = 0; n < p.count; n++) {
        const float *f = &p.data[n * SWC_PANEL_STRIDE];
        bool tall = f[SWC_PANEL_SIZE] < f[SWC_PANEL_SIZE + 1];
        int limit = tall ? SWC_ATLAS_TALL_COUNT : SWC_ATLAS_WIDE_COUNT;
        CHECK(p.cell_a[n] >= 0 && p.cell_a[n] < limit);
        CHECK(p.cell_b[n] >= 0 && p.cell_b[n] < limit);
        CHECK(p.cell_a[n] != p.cell_b[n]);
        (tall ? seen_tall : seen_wide)[p.cell_a[n]]++;
        CHECK(f[SWC_PANEL_FIT] >= 1.0f && f[SWC_PANEL_FIT + 1] >= 1.0f);
    }
    /* Round robin: every ad is on show somewhere. */
    for (int k = 0; k < SWC_ATLAS_WIDE_COUNT; k++)
        CHECK(seen_wide[k] > 0);
    for (int k = 0; k < SWC_ATLAS_TALL_COUNT; k++)
        CHECK(seen_tall[k] > 0);
    swc_holo_free_panels(&p);
}

