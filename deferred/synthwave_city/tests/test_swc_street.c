static void test_traffic_density_thins_gently(void) {
    CHECK_NEAR(swc_street_traffic_density(1.0), 1.0, 1e-12);
    CHECK_NEAR(swc_street_traffic_density(0.6), sqrt(0.6), 1e-12);
    CHECK_NEAR(swc_street_traffic_density(0.0), sqrt(0.05), 1e-12);
    CHECK_NEAR(swc_street_traffic_density(9.0), 1.0, 1e-12);
}

static void test_lane_table_matches_the_web_version(void) {
    for (int i = 0; i < N_GOLDEN; i++) {
        const GoldenCase *g = &GOLDEN[i];
        CHECK_NEAR(swc_street_traffic_density(g->quality), g->traffic, 1e-12);
        build_case(g);
        CHECK_EQ_INT(table.record_count, g->records);
        CHECK_EQ_INT(table.slots, g->slots);
        CHECK_NEAR(table.min_spacing, g->min_spacing, 1e-9);
        CHECK_NEAR(table.max_spacing, g->max_spacing, 1e-9);
        double sums[4] = {0, 0, 0, 0};
        for (int t = 0; t < SWC_CELLS * SWC_STREET_LANE_ROWS; t++)
            for (int k = 0; k < 4; k++)
                sums[k] += (double)table.data[t * 4 + k];
        for (int k = 0; k < 4; k++)
            CHECK_NEAR(sums[k], g->col_sums[k], 1e-6);
        for (int k = 0; k < 16; k++)
            CHECK_NEAR(table.data[k], g->data_first[k], 1e-6);
        static const int at[5] = {0, 1, 40 * 3 + 5, 40 * 7 + 21, 40 * 11 + 39};
        for (int t = 0; t < 5; t++)
            for (int k = 0; k < 4; k++)
                CHECK_NEAR(table.data[at[t] * 4 + k], g->data_at[t][k], 1e-6);
        for (int p = 0; p < g->pick_count; p++) {
            const SwcLaneRec *r = &table.records[g->pick[p]];
            const double *e = g->pick_rec[p];
            CHECK_EQ_INT(r->axis, (int)e[0]);
            CHECK_EQ_INT(r->line, (int)e[1]);
            CHECK_EQ_INT(r->row, (int)e[2]);
            CHECK_NEAR(r->offset, e[3], 1e-9);
            CHECK_EQ_INT(r->dir, (int)e[4]);
            CHECK_EQ_INT(r->laps, (int)e[5]);
            CHECK_EQ_INT(r->count, (int)e[6]);
            CHECK_NEAR(r->phase, e[7], 1e-9);
            CHECK_NEAR(r->spacing, e[8], 1e-9);
        }
        double rs = 0;
        for (int r = 0; r < table.record_count; r++) {
            const SwcLaneRec *x = &table.records[r];
            rs += x->offset * 3 + x->dir * 5 + x->laps * 7 + x->count * 11 + (double)x->phase * 13 +
                  x->line * 17 + x->row * 19;
        }
        CHECK_NEAR(rs, g->rec_sum, 1e-6);
    }
}

