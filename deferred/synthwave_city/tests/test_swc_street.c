static void test_each_mesh_part_is_wound_outward_and_inside_its_dimensions(void) {
    static SwcCarMesh mesh;
    swc_street_build_car_mesh(&mesh);
    for (int part = 0; part < 3; part++) {
        double volume = 0;
        for (int t = 0; t < mesh.index_count; t += 3) {
            int a = mesh.index[t], b = mesh.index[t + 1], c = mesh.index[t + 2];
            if ((int)mesh.part[a] != part)
                continue;
            CHECK_EQ_INT((int)mesh.part[b], part);
            CHECK_EQ_INT((int)mesh.part[c], part);
            const float *pa = &mesh.position[a * 3], *pb = &mesh.position[b * 3], *pc = &mesh.position[c * 3];
            volume += ((double)pa[0] * ((double)pb[1] * pc[2] - (double)pb[2] * pc[1]) -
                       (double)pa[1] * ((double)pb[0] * pc[2] - (double)pb[2] * pc[0]) +
                       (double)pa[2] * ((double)pb[0] * pc[1] - (double)pb[1] * pc[0])) /
                      6.0;
        }
        CHECK(volume > 0.0);
    }
    for (int i = 0; i < mesh.vertex_count; i++) {
        CHECK(fabs((double)mesh.position[i * 3]) <= SWC_CAR_DIMS[0] + 1e-6);
        CHECK(fabs((double)mesh.position[i * 3 + 2]) <= SWC_CAR_DIMS[2] + 0.03 + 1e-6);
        CHECK((double)mesh.position[i * 3 + 1] <= SWC_CAR_DIMS[1] + 1e-6);
        CHECK(fabs((double)mesh.alt[i * 3]) <= SWC_VAN_DIMS[0] + 1e-6);
        CHECK((double)mesh.alt[i * 3 + 1] <= SWC_VAN_DIMS[1] + 1e-6);
    }
}

static void test_a_lane_never_holds_cars_closer_than_the_minimum_gap(void) {
    build_case(&GOLDEN[0]);
    for (int r = 0; r < table.record_count; r++) {
        const SwcLaneRec *rec = &table.records[r];
        CHECK(rec->count >= 1 && rec->count <= (int)(SWC_TILE / SWC_STREET_MIN_SPACING));
        CHECK(rec->laps >= 6 && rec->laps <= 21);
        if (rec->count < 2)
            continue;
        CHECK(rec->spacing * (1.0 - swc_street_jitter_range(rec->spacing)) >= SWC_STREET_MIN_GAP - 1e-9);
    }
}

