/* The most boxes any cell holds at street level. */
static int max_street_boxes(void) {
    int most = 0;
    for (int cell = 0; cell < SWC_CELL_COUNT; cell++) {
        int n = 0;
        for (int i = city.box_start[cell]; i < city.box_start[cell + 1]; i++)
            if ((double)city.boxes[city.box_list[i]].y0 < SWC_ALLEY_GROUND)
                n++;
        if (n > most)
            most = n;
    }
    return most;
}

static void test_the_alley_table_matches_the_web_version(void) {
    for (int i = 0; i < N_GOLDEN; i++) {
        const GoldenAlleyCase *g = &GOLDEN_BLOCK[i];
        build_case(g->seed);
        CHECK_EQ_INT(alleys.width, SWC_CELLS * SWC_ALLEY_TEXELS);
        CHECK_EQ_INT(alleys.height, SWC_CELLS);
        CHECK_EQ_INT(alleys.count, g->count);
        double sums[4] = {0, 0, 0, 0}, weighted = 0;
        int nonzero = 0;
        int n = alleys.width * alleys.height;
        for (int t = 0; t < n; t++) {
            for (int k = 0; k < 4; k++)
                sums[k] += (double)alleys.data[t * 4 + k];
            if (alleys.data[t * 4 + 3] > 0.0f)
                nonzero++;
            double next = t * 4 + 4 < n * 4 ? (double)alleys.data[t * 4 + 4] : 0.0;
            weighted +=
                ((double)alleys.data[t * 4] * 3 + (double)alleys.data[t * 4 + 1] * 5 +
                 (double)alleys.data[t * 4 + 2] * 7 + (double)alleys.data[t * 4 + 3] * 11 + next * 13) *
                (double)((t % 13) + 1);
        }
        CHECK_EQ_INT(nonzero, g->nonzero);
        for (int k = 0; k < 4; k++)
            CHECK_NEAR(sums[k], g->sums[k], 1e-6);
        CHECK_NEAR(weighted, g->weighted, 1e-3);
        static const int at[6] = {0,
                                  5,
                                  4 * 40 * 7 + 21 * 4,
                                  4 * 40 * 20 + 4 * 17 + 2,
                                  4 * 40 * 39 + 4 * 39 + 2,
                                  4 * 40 * 11 + 4 * 25};
        for (int t = 0; t < 6; t++)
            for (int k = 0; k < 8; k++)
                CHECK_NEAR(alleys.data[at[t] * 4 + k], g->texels[t][k], 0.0);
        /* Far fewer boxes per cell than the scratch the finder works in. */
        CHECK_EQ_INT(max_street_boxes(), g->max_per_cell);
        CHECK(g->max_per_cell < 64);
    }
}

