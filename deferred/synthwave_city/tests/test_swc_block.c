/* A street-level box's footprint in its cell's own coordinates. */
static void footprint(const SwcBox *b, double *x0, double *x1, double *z0, double *z1) {
    double x = (double)b->cx, z = (double)b->cz;
    double hx = (double)b->sx / 2.0, hz = (double)b->sz / 2.0;
    double ox = floor(x / SWC_CELL) * SWC_CELL, oz = floor(z / SWC_CELL) * SWC_CELL;
    *x0 = x - hx - ox;
    *x1 = x + hx - ox;
    *z0 = z - hz - oz;
    *z1 = z + hz - oz;
}

static void test_alleys_are_between_the_lots_and_only_where_no_building_stands(void) {
    static const uint32_t seeds[2] = {1u, 2049u};
    for (int s = 0; s < 2; s++) {
        build_case(seeds[s]);
        int with_alleys = 0, built = 0;
        for (int cell = 0; cell < SWC_CELL_COUNT; cell++) {
            int cx = cell % SWC_CELLS, cz = cell / SWC_CELLS;
            int d = city.cells[cell].district;
            int found = 0;
            for (int axis = 0; axis < 2; axis++) {
                int at = (cz * alleys.width + cx * SWC_ALLEY_TEXELS + axis * 2) * 4;
                int n = (int)alleys.data[at + 3];
                CHECK(n <= SWC_ALLEYS_PER_AXIS);
                found += n;
                for (int k = 0; k < n; k++) {
                    double centre = alleys.data[at + k], half = alleys.data[at + 4 + k];
                    CHECK(half * 2.0 >= SWC_ALLEY_MIN_WIDTH - 1e-6);
                    /* No street-level box reaches into the band, anywhere along the block. */
                    for (int i = city.box_start[cell]; i < city.box_start[cell + 1]; i++) {
                        const SwcBox *b = &city.boxes[city.box_list[i]];
                        if ((double)b->y0 >= SWC_ALLEY_GROUND)
                            continue;
                        double x0, x1, z0, z1;
                        footprint(b, &x0, &x1, &z0, &z1);
                        double lo = axis == 0 ? z0 : x0, hi = axis == 0 ? z1 : x1;
                        CHECK(hi <= centre - half + 1e-4 || lo >= centre + half - 1e-4);
                    }
                }
            }
            if (d == SWC_PLAZA || d == SWC_MEGA) {
                CHECK_EQ_INT(found, 0);
                continue;
            }
            built++;
            if (found > 0)
                with_alleys++;
        }
        CHECK(alleys.count > 1000);
        CHECK((double)with_alleys / (double)built > 0.6);
    }
}

