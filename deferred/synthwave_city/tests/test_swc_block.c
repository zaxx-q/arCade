/* Every shown block walker for a few cameras and loop phases, visited by `visit`. */
typedef void (*WalkerVisit)(const SwcBlockWalker *w);

static void each_walker(int cameras, const double *loops, int loop_count, uint32_t seed, int per_cell,
                        WalkerVisit visit) {
    rng_state = seed;
    for (int c = 0; c < cameras; c++) {
        double cam_x = rng_unit() * SWC_TILE, cam_z = rng_unit() * SWC_TILE;
        for (int l = 0; l < loop_count; l++)
            for (int dz = -SWC_BLOCK_REACH; dz <= SWC_BLOCK_REACH; dz++)
                for (int dx = -SWC_BLOCK_REACH; dx <= SWC_BLOCK_REACH; dx++)
                    for (int p = 0; p < per_cell; p++) {
                        SwcBlockWalker w = swc_street_block_walker_at(&alleys, &city, cam_x, cam_z, loops[l],
                                                                      dx, dz, p, per_cell);
                        if (w.show)
                            visit(&w);
                    }
    }
}

static int walk_outside, walk_modes[4], walk_total;
static double walk_nearest, walk_centre, walk_fixture_margin;

static void visit_clearance(const SwcBlockWalker *w) {
    double lx = swc_wrap(w->x, SWC_TILE) - w->cx * SWC_CELL, lz = swc_wrap(w->z, SWC_TILE) - w->cz * SWC_CELL;
    SwcRect rect = swc_street_cell_rect(w->cx, w->cz);
    walk_total++;
    walk_modes[w->mode]++;
    /* Inside its block, so off the sidewalks and the roads. */
    if (lx < rect.x0 || lx > rect.x1 || lz < rect.z0 || lz > rect.z1)
        walk_outside++;
    int cell = w->cz * SWC_CELLS + w->cx;
    for (int i = city.box_start[cell]; i < city.box_start[cell + 1]; i++) {
        const SwcBox *b = &city.boxes[city.box_list[i]];
        if ((double)b->y0 >= 2.5)
            continue;
        double x0, x1, z0, z1;
        footprint(b, &x0, &x1, &z0, &z1);
        double gx = fmax(fmax(x0 - lx, 0.0), lx - x1), gz = fmax(fmax(z0 - lz, 0.0), lz - z1);
        double g = hypot(gx, gz);
        if (g < walk_nearest)
            walk_nearest = g;
    }
}

static void test_people_never_stand_in_a_building_or_a_road(void) {
    static const double loops[3] = {0.0, 0.37, 0.81};
    static const uint32_t seeds[2] = {1u, 2049u};
    for (int s = 0; s < 2; s++) {
        build_case(seeds[s]);
        walk_outside = 0;
        walk_total = 0;
        memset(walk_modes, 0, sizeof(walk_modes));
        walk_nearest = 1e9;
        each_walker(12, loops, 3, 7u + (uint32_t)s, SWC_BLOCK_SLOTS, visit_clearance);
        for (int m = 0; m < 4; m++)
            CHECK(walk_modes[m] > 0);
        CHECK_EQ_INT(walk_outside, 0);
        /* At least half a metre from every wall: a body is about 0.3 m either side of its centre. */
        CHECK(walk_nearest >= 0.5);
    }
}

static void visit_plaza(const SwcBlockWalker *w) {
    if (w->mode == SWC_BLOCK_ALLEY)
        return;
    SwcRect rect = swc_street_cell_rect(w->cx, w->cz);
    double mx = w->cx * SWC_CELL + (rect.x0 + rect.x1) / 2.0,
           mz = w->cz * SWC_CELL + (rect.z0 + rect.z1) / 2.0;
    double x = swc_wrap(w->x, SWC_TILE), z = swc_wrap(w->z, SWC_TILE);
    walk_total++;
    double c = hypot(x - mx, z - mz);
    if (c < walk_centre)
        walk_centre = c;
    for (int i = 0; i < city.site_count; i++) {
        const SwcSite *s = &city.sites[i];
        if (s->kind != SWC_SITE_PILLAR && s->kind != SWC_SITE_SEARCHLIGHT)
            continue;
        if (fabs(s->x - x) > 40.0 || fabs(s->z - z) > 40.0)
            continue;
        double clear = s->kind == SWC_SITE_PILLAR ? s->w + 0.5 : 1.5;
        double m = hypot(x - s->x, z - s->z) - clear;
        if (m < walk_fixture_margin)
            walk_fixture_margin = m;
    }
}

static void test_plaza_people_keep_off_the_centre_the_pillar_and_the_searchlights(void) {
    static const double loops[2] = {0.2, 0.6};
    static const uint32_t seeds[2] = {1u, 2049u};
    for (int s = 0; s < 2; s++) {
        build_case(seeds[s]);
        walk_total = 0;
        walk_centre = 1e9;
        walk_fixture_margin = 1e9;
        each_walker(12, loops, 2, 70u + (uint32_t)s, SWC_BLOCK_SLOTS, visit_plaza);
        CHECK(walk_total > 100);
        CHECK(walk_centre >= SWC_PLAZA_CROSS_CENTRE - 1e-6);
        CHECK(walk_fixture_margin >= 0.0);
    }
}

static void test_people_come_back_where_they_started_and_walk_at_a_human_pace(void) {
    build_case(1u);
    rng_state = 3u;
    int moving = 0;
    for (int c = 0; c < 6; c++) {
        double cam_x = rng_unit() * SWC_TILE, cam_z = rng_unit() * SWC_TILE;
        for (int dz = -1; dz <= 1; dz++)
            for (int dx = -1; dx <= 1; dx++)
                for (int p = 0; p < SWC_BLOCK_SLOTS; p++) {
                    SwcBlockWalker a = swc_street_block_walker_at(&alleys, &city, cam_x, cam_z, 0.0, dx, dz,
                                                                  p, SWC_BLOCK_SLOTS);
                    if (!a.show)
                        continue;
                    SwcBlockWalker b = swc_street_block_walker_at(&alleys, &city, cam_x, cam_z, 1.0, dx, dz,
                                                                  p, SWC_BLOCK_SLOTS);
                    CHECK(fabs(a.x - b.x) + fabs(a.z - b.z) < 1e-6);
                    if (a.laps == 0)
                        continue;
                    moving++;
                    double speed = (double)a.laps * a.lap_length / SWC_LOOP_SECONDS;
                    CHECK(speed > 0.5);
                    CHECK(speed < 1.8);
                }
    }
    CHECK(moving > 200);
}

static int count_shown(int per_cell) {
    int n = 0;
    for (int dz = -SWC_BLOCK_REACH; dz <= SWC_BLOCK_REACH; dz++)
        for (int dx = -SWC_BLOCK_REACH; dx <= SWC_BLOCK_REACH; dx++)
            for (int p = 0; p < per_cell; p++)
                if (swc_street_block_walker_at(&alleys, &city, 3200.0, 3200.0, 0.3, dx, dz, p, per_cell).show)
                    n++;
    return n;
}

static void test_people_thin_out_with_the_tier_and_vanish_where_there_are_no_crowds(void) {
    build_case(1u);
    int full = count_shown(SWC_BLOCK_SLOTS);
    int thin = count_shown((int)floor((double)SWC_BLOCK_SLOTS * 0.6 + 0.5));
    CHECK(full > 0);
    CHECK(thin < full);
    CHECK_EQ_INT(count_shown(0), 0);
}

