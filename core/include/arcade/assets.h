/* Game assets (fonts, sounds, textures, songs). Pure C99: no raylib in this file.
 *
 * Everything in assets/ is compiled INTO the executable (cmake/embed_assets.cmake), so the game is one single
 * file and needs nothing next to it. Games ask for an asset by its path inside assets/, for example
 * "fonts/PoiretOne-Regular.ttf" or "beatmaps/songs.txt", and never open it with fopen():
 *
 *   ArcAsset a = arc_asset_load(ctx->assets_dir, "beatmaps/songs.txt");
 *   if (a.data != NULL) { ... use a.data[0 .. a.size-1] ... }
 *   arc_asset_release(&a);
 *
 * `dir` is an OPTIONAL override folder (the hub's --assets-dir): when it is not empty and holds the file,
 * that copy is used, so a developer can try a new song or font without rebuilding. Otherwise (the normal
 * case: NULL or
 * "") the copy inside the executable is used. */
#ifndef ARCADE_ASSETS_H
#define ARCADE_ASSETS_H

#include "arcade/common.h"

/* One embedded file. The table is generated by CMake (cmake/embed_assets.cmake), sorted by name. It holds
 * every file of assets/, plus two legal texts from the repository root: "LICENSE" and
 * "THIRD_PARTY_NOTICES.md". */
typedef struct ArcAssetEntry {
    const char *name;          /* path inside assets/, with '/' on every OS */
    const unsigned char *data; /* followed by one extra 0 byte that `size` does not count */
    size_t size;
} ArcAssetEntry;

extern const ArcAssetEntry g_arcade_assets[];
extern const int g_arcade_asset_count;

/* Bytes of one asset. data == NULL means "not found". */
typedef struct ArcAsset {
    const unsigned char *data; /* always followed by one 0 byte, so a text asset is also a valid C string */
    size_t size;               /* without that 0 byte */
    void *heap;                /* private: the memory to free when the bytes were read from a folder */
} ArcAsset;

/* Finds assets/<name>: first in the override folder `dir` (skipped when dir is NULL or ""), then in the copy
 * built into the executable. Check .data for NULL; call arc_asset_release() when you are done with the bytes
 * (a no-op for the built-in copy, which lives as long as the program). */
ArcAsset arc_asset_load(const char *dir, const char *name);

/* Reads a whole file from disk (binary mode) into memory. Same result type, so the same release call. */
ArcAsset arc_asset_read_file(const char *path);

void arc_asset_release(ArcAsset *a); /* safe on a not-found asset and safe to call twice */

#endif
