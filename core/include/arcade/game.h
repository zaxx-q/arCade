/* The contract between the hub and every game. See games/AGENTS.md. Pure C99, no raylib. */
#ifndef ARCADE_GAME_H
#define ARCADE_GAME_H

#include "arcade/common.h"

#define GAME_BOARD_LEN 48 /* size of GameContext.board, NUL included */

typedef struct GameContext {
    const char *player;          /* name for the leaderboard                                    */
    unsigned seed;               /* RNG seed (fixed in tests / smoke runs)                      */
    bool headless;               /* CI smoke run: scripted input, bounded frames, no audio      */
    int max_frames;              /* >0 only when headless: stop after this many frames          */
    const char *data_dir;        /* writable folder (scores, replays)                           */
    const char *assets_dir;      /* optional override folder for arc_asset_load(); NULL or "" = built in */
    const char *screenshot_path; /* NULL unless a smoke run wants periodic PNG snapshots        */
    /* OPTIONAL OUTPUT, NULL when nobody listens (smoke runs, tests): a buffer of GAME_BOARD_LEN bytes, empty
     * on entry. A game with several modes or levels writes the name of this run's high-score table into it
     * before play() returns (e.g. "Dodge / Bopeebo / normal"); the hub then records and ranks the score in
     * that table only (see leaderboard.h, "boards"). Left empty: one table for the whole game. Always check
     * for NULL. A pointer to writable memory is fine in a const context: the game may fill the buffer, not
     * re-point it. */
    char *board;
} GameContext;

typedef struct GameResult {
    int score;     /* >= 0 */
    bool finished; /* true = the run ended (game over, level done, or leaving a game that has no end): the
                      score is recorded; false = the player abandoned it with ESC: nothing is recorded */
} GameResult;

typedef GameResult (*GamePlayFn)(const GameContext *ctx);

typedef struct GameDef {
    const char *id;       /* equals the folder name, e.g. "echo_maze"          */
    const char *title;    /* menu title                                        */
    const char *tagline;  /* one-line hook shown on the menu card              */
    const char *controls; /* short controls hint shown on the menu card        */
    int order;            /* menu position: lower first, ties broken by id     */
    GamePlayFn play;      /* runs the whole game loop and returns the result   */
} GameDef;

/* Generated by CMake (cmake/ArcadeRegistry.cmake) from the folders in games/ and deferred/.
 * g_arcade_games    = games/    -> shown on the hub menu
 * g_arcade_deferred = deferred/ -> parked: same contract, but only reachable through the hub's archive */
extern const GameDef *const g_arcade_games[];
extern const int g_arcade_game_count;
extern const GameDef *const g_arcade_deferred[];
extern const int g_arcade_deferred_count;

#endif
