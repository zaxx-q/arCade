/* The contract between the hub and every game. See games/AGENTS.md. Pure C99, no raylib. */
#ifndef ARCADE_GAME_H
#define ARCADE_GAME_H

#include "arcade/common.h"

typedef struct GameContext {
    const char *player;          /* name for the leaderboard                                    */
    unsigned seed;               /* RNG seed (fixed in tests / smoke runs)                      */
    bool headless;               /* CI smoke run: scripted input, bounded frames, no audio      */
    int max_frames;              /* >0 only when headless: stop after this many frames          */
    const char *data_dir;        /* writable folder (scores, replays)                           */
    const char *assets_dir;      /* read-only assets folder                                     */
    const char *screenshot_path; /* NULL unless a smoke run wants periodic PNG snapshots        */
} GameContext;

typedef struct GameResult {
    int score;     /* >= 0 */
    bool finished; /* true = game over / level done (score is recorded); false = player pressed ESC */
} GameResult;

typedef GameResult (*GamePlayFn)(const GameContext *ctx);

typedef struct GameDef {
    const char *id;       /* equals the folder name, e.g. "echo_maze"          */
    const char *title;    /* menu title                                        */
    const char *tagline;  /* one-line hook shown on the menu card              */
    const char *controls; /* short controls hint shown on the menu card        */
    int order;            /* menu position: lower first, ties broken by id     */
    bool ranked;          /* false = never written to the leaderboard          */
    GamePlayFn play;      /* runs the whole game loop and returns the result   */
} GameDef;

/* Generated by CMake (cmake/ArcadeRegistry.cmake) from the folders in games/. */
extern const GameDef *const g_arcade_games[];
extern const int g_arcade_game_count;

#endif
